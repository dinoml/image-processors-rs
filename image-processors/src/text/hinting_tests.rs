use super::Interpreter;

fn arithmetic_program(a: i16, b: i16, opcode: u8) -> Vec<u8> {
    // PUSHB storage slot, PUSHW numerator/denominator, operation, WS.
    let mut program = vec![0xb0, 0, 0xb9];
    program.extend_from_slice(&a.to_be_bytes());
    program.extend_from_slice(&b.to_be_bytes());
    program.extend_from_slice(&[opcode, 0x42]);
    program
}

#[test]
fn div_bytecode_truncates_signed_distances_toward_zero() {
    // FreeType2.13.2 Ins_DIV uses FT_MulDiv_No_Round. In particular,
    // 386*64/256 is96 rather than97, affecting real Arial stem placement.
    for (a, b, expected) in [
        (386, 256, 96),
        (-386, 256, -96),
        (386, -256, -96),
        (-386, -256, 96),
        (387, 256, 96),
        (-387, 256, -96),
        (1, 3, 21),
    ] {
        let mut interpreter = Interpreter::new(20, 2048, 4, 1, &[])
            .expect("the bounded arithmetic interpreter must initialize");
        interpreter
            .execute(&arithmetic_program(a, b, 0x62), 0)
            .expect("valid DIV bytecode must execute");
        assert_eq!(interpreter.storage[0], expected, "DIV {a} / {b}");
    }
}

#[test]
fn mul_retains_nearest_rounding_and_div_zero_returns_an_error() {
    let mut interpreter = Interpreter::new(20, 2048, 4, 1, &[])
        .expect("the bounded arithmetic interpreter must initialize");
    interpreter
        .execute(&arithmetic_program(386, 16, 0x63), 0)
        .expect("valid MUL bytecode must execute");
    assert_eq!(interpreter.storage[0], 97, "MUL still rounds386*16/64");
    assert!(interpreter
        .execute(&arithmetic_program(386, 0, 0x62), 0)
        .is_err());
    assert_eq!(
        interpreter.storage[0], 97,
        "invalid DIV must not execute WS"
    );
}

#[test]
fn arithmetic_results_preserve_reference_signed_32_bit_stack_width() {
    // Results were independently checked against the existing FreeType2.13.2
    // Windows library (sizeof(FT_Long)==4), not generated by this interpreter.
    for (a, b, opcode, expected) in [
        (i32::MAX, 1, 0x62, -64),
        (i32::MAX, -1, 0x62, 64),
        (i32::MIN, 1, 0x62, 0),
        (i32::MIN, -1, 0x62, 0),
        (i32::MAX, 128, 0x63, -2),
        (i32::MIN, 128, 0x63, 0),
    ] {
        let mut interpreter = Interpreter::new(20, 2048, 4, 1, &[])
            .expect("the bounded arithmetic interpreter must initialize");
        interpreter.stack = vec![0, i64::from(a), i64::from(b)];
        interpreter
            .execute(&[opcode, 0x42], 0)
            .expect("valid boundary arithmetic must execute");
        assert_eq!(interpreter.storage[0], expected);
    }
}
